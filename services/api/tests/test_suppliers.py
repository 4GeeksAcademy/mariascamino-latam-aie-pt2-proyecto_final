"""/suppliers — directory of suppliers (API-042, group: suppliers)."""

import database

SUPPLIER = {
    "name": "Acme Medical",
    "country": "USA",
    "categories": ["medical_supplies"],
    "monthly_rate": 1200.5,
    "currency": "USD",
}


def _create(client, headers, **overrides):
    return client.post("/suppliers", headers=headers, json={**SUPPLIER, **overrides})


# ---------------------------------------------------------------- happy path
def test_create_supplier_defaults_to_active_and_server_sets_updated_at(client, user, auth_headers):
    response = _create(client, auth_headers(user))

    assert response.status_code == 201
    stored = database.suppliers_table.all()[0]
    assert stored["status"] == "active"
    assert stored["updated_at"]  # generated by the server, not the client


def test_list_can_be_filtered_by_country_and_category(client, user, auth_headers):
    headers = auth_headers(user)
    _create(client, headers, name="US lab", categories=["laboratory_services"])
    _create(client, headers, name="UK supplies", country="UK", currency="GBP", categories=["medical_supplies"])

    by_country = client.get("/suppliers?country=UK", headers=headers).json()
    by_category = client.get("/suppliers?category=laboratory_services", headers=headers).json()
    both = client.get("/suppliers?country=UK&category=laboratory_services", headers=headers).json()

    assert [s["name"] for s in by_country] == ["UK supplies"]
    assert [s["name"] for s in by_category] == ["US lab"]
    assert both == []


def test_update_rate_and_status_and_delete(client, user, auth_headers):
    headers = auth_headers(user)
    supplier_id = _create(client, headers).json()["id"]

    rate = client.patch(f"/suppliers/{supplier_id}/rate", headers=headers, json={"monthly_rate": 99.9})
    status = client.patch(f"/suppliers/{supplier_id}/status", headers=headers, json={"status": "suspended"})
    deleted = client.delete(f"/suppliers/{supplier_id}", headers=headers)

    assert rate.status_code == status.status_code == deleted.status_code == 200
    assert database.suppliers_table.all() == []


# ---------------------------------------------------------------- edge cases
def test_monthly_rate_boundary_zero_is_rejected_smallest_positive_accepted(client, user, auth_headers):
    headers = auth_headers(user)

    zero = _create(client, headers, monthly_rate=0)
    tiny = _create(client, headers, monthly_rate=0.01)

    assert zero.status_code == 422
    assert tiny.status_code == 201


def test_currency_must_match_the_country(client, user, auth_headers):
    response = _create(client, auth_headers(user), country="UK", currency="USD")

    assert response.status_code == 422
    assert database.suppliers_table.all() == []


def test_a_supplier_needs_at_least_one_category(client, user, auth_headers):
    assert _create(client, auth_headers(user), categories=[]).status_code == 422


def test_renewal_date_must_be_a_real_calendar_date(client, user, auth_headers):
    headers = auth_headers(user)

    assert _create(client, headers, contract_renewal_date="2026-02-30").status_code == 422
    assert _create(client, headers, contract_renewal_date="2026-12-31").status_code == 201


# -------------------------------------------------------------- failure modes
def test_unknown_supplier_returns_404_for_every_action(client, user, auth_headers):
    headers = auth_headers(user)

    assert client.get("/suppliers/999", headers=headers).status_code == 404
    assert client.patch("/suppliers/999/rate", headers=headers, json={"monthly_rate": 5}).status_code == 404
    assert client.patch("/suppliers/999/status", headers=headers, json={"status": "active"}).status_code == 404
    assert client.delete("/suppliers/999", headers=headers).status_code == 404


def test_invalid_filter_value_is_rejected(client, user, auth_headers):
    assert client.get("/suppliers?country=FR", headers=auth_headers(user)).status_code == 422


def test_negative_rate_update_is_rejected_and_keeps_the_old_rate(client, user, auth_headers):
    headers = auth_headers(user)
    supplier_id = _create(client, headers).json()["id"]

    response = client.patch(f"/suppliers/{supplier_id}/rate", headers=headers, json={"monthly_rate": -5})

    assert response.status_code == 422
    assert database.suppliers_table.get(doc_id=supplier_id)["monthly_rate"] == SUPPLIER["monthly_rate"]


def test_suppliers_require_login(client):
    assert client.get("/suppliers").status_code == 401
    assert client.post("/suppliers", json=SUPPLIER).status_code == 401
