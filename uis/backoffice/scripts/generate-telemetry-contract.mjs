#!/usr/bin/env node
/**
 * Generates lib/telemetry-contract.generated.ts from the approved Phase 1
 * contract (docs/telemetry/event-schemas.json).
 *
 * The backoffice never hand-writes event names, schema versions or property
 * allowlists: they come from the same JSON Schema the collector will use, so
 * the two cannot drift. A Jest test fails if this file is stale.
 *
 *   npm run telemetry:contract
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SCHEMA_PATH = resolve(here, "../../../docs/telemetry/event-schemas.json");
export const OUTPUT_PATH = resolve(here, "../lib/telemetry-contract.generated.ts");

function propertySpec(schema) {
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  const spec = { types };
  if (schema.enum) spec.enum = schema.enum.filter((v) => v !== null);
  if (schema.minimum !== undefined) spec.minimum = schema.minimum;
  if (schema.maximum !== undefined) spec.maximum = schema.maximum;
  if (schema.maxLength !== undefined) spec.maxLength = schema.maxLength;
  if (schema.maxItems !== undefined) spec.maxItems = schema.maxItems;
  if (schema.pattern) spec.pattern = schema.pattern;
  if (schema.items?.pattern) spec.itemPattern = schema.items.pattern;
  return spec;
}

export function buildContract(schemaJson) {
  const events = {};
  for (const [name, def] of Object.entries(schemaJson.definitions)) {
    if (name === "envelope") continue;
    const own = def.allOf[1].properties;
    const props = own.properties;
    const meta = def["x-healthcore"] ?? {};
    events[name] = {
      schemaVersion: own.schemaVersion.const,
      mandatory: meta.classification === "mandatory",
      required: props.required ?? [],
      properties: Object.fromEntries(
        Object.entries(props.properties).map(([key, schema]) => [key, propertySpec(schema)])
      ),
    };
  }
  return { version: schemaJson["x-version"], events };
}

export function render(contract) {
  return `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-telemetry-contract.mjs — DO NOT EDIT.
// Source of truth: docs/telemetry/event-schemas.json (approved Phase 1 plan).

export type PropertySpec = {
  types: string[];
  enum?: unknown[];
  minimum?: number;
  maximum?: number;
  maxLength?: number;
  maxItems?: number;
  pattern?: string;
  itemPattern?: string;
};

export type EventContract = {
  schemaVersion: string;
  mandatory: boolean;
  required: string[];
  properties: Record<string, PropertySpec>;
};

/** Version of the event catalogue (event-schemas.json x-version). */
export const TELEMETRY_CONTRACT_VERSION = ${JSON.stringify(contract.version)};

export const TELEMETRY_CONTRACT: Record<string, EventContract> = ${JSON.stringify(contract.events, null, 2)};
`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const contract = buildContract(JSON.parse(readFileSync(SCHEMA_PATH, "utf8")));
  writeFileSync(OUTPUT_PATH, render(contract));
  console.log(`telemetry contract: ${Object.keys(contract.events).length} events → ${OUTPUT_PATH}`);
}
